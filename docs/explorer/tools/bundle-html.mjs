#!/usr/bin/env node
// Builds the standalone explorer page: one HTML file that works from disk (file://), with no server and no build step.
//   node bundle-html.mjs <data-entry.js> <out.html> [--engine <explorer-engine.js>] [--css <explorer.css>]
// Defaults: explorer-engine.js and explorer.css next to the data entry. The same data and engine files are what a
// React/Next/Vue/Svelte shell imports, so both versions always show the same thing.
// Supported module syntax (deliberately small, no dependencies):
//   import { a, b as c } from "./x.js" · import x from "./x.js" · export default … · export const|let x = …
//   export function f() {} · export { a, b }
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";

const args = process.argv.slice(2);
const flag = name => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const engineArg = flag("--engine"), cssArg = flag("--css");
const [entry, out] = args;
if (!entry || !out) { console.error("usage: node bundle-html.mjs <data-entry.js> <out.html> [--engine file] [--css file]"); process.exit(2); }
const dir = dirname(resolve(entry));
const enginePath = resolve(engineArg || `${dir}/explorer-engine.js`);
const cssPath = resolve(cssArg || `${dir}/explorer.css`);

const modules = new Map();   // absolute path → converted body
function load(path) {
  if (modules.has(path)) return;
  modules.set(path, null);
  let src = readFileSync(path, "utf8");
  const exportsAfter = [];
  src = src.replace(/^import\s+(?:(\w+)|\{([^}]*)\})\s+from\s+["']([^"']+)["'];?[ \t]*$/gm, (_, def, names, spec) => {
    if (!spec.startsWith(".")) throw new Error(`${path}: only relative imports can be inlined (${spec})`);
    const dep = resolve(dirname(path), spec);
    load(dep);
    const key = JSON.stringify(relative(dir, dep));
    if (def) return `const ${def} = __req(${key}).default;`;
    const parts = names.split(",").map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ": "));
    return `const { ${parts.join(", ")} } = __req(${key});`;
  });
  src = src.replace(/^export\s+default\s+/m, "__exp.default = ");
  src = src.replace(/^export\s+(const|let)\s+(\w+)\s*=/gm, (_, kw, name) => `${kw} ${name} = __exp.${name} =`);
  src = src.replace(/^export\s+(async\s+)?function\s+(\w+)/gm, (_, a, name) => { exportsAfter.push(name); return `${a || ""}function ${name}`; });
  src = src.replace(/^export\s*\{([^}]*)\};?/gm, (_, names) => `Object.assign(__exp, { ${names.replace(/(\w+)\s+as\s+(\w+)/g, "$2: $1")} });`);
  if (/^\s*(import|export)\s/m.test(src)) throw new Error(`${path}: unsupported import/export form (see the header of bundle-html.mjs)`);
  modules.set(path, src + (exportsAfter.length ? `\nObject.assign(__exp, { ${exportsAfter.join(", ")} });` : ""));
}
load(enginePath);
load(resolve(entry));

const defs = [...modules].map(([path, body]) =>
  `__defs[${JSON.stringify(relative(dir, path))}] = function (__exp) {\n${body}\n};`).join("\n");
const css = readFileSync(cssPath, "utf8");
const title = (readFileSync(resolve(entry), "utf8").match(/title:\s*"([^"]+)"/) || [, "Project explorer"])[1];
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title.replace(/[<&]/g, "")}</title>
<!-- Generated by bundle-html.mjs from ${relative(dirname(resolve(out)), resolve(entry))}: edit the data, then rebuild. -->
<style>
html, body { margin: 0; background: #f6f7f9; }
@media (prefers-color-scheme: dark) { html, body { background: #0f1218; } }
${css}
</style>
</head>
<body>
<div id="explorer"></div>
<script>
(() => {
const __defs = {}, __cache = {};
const __req = key => { if (!__cache[key]) { const e = __cache[key] = {}; __defs[key](e); } return __cache[key]; };
${defs}
const engine = __req(${JSON.stringify(relative(dir, enginePath))});
const data = __req(${JSON.stringify(relative(dir, resolve(entry)))}).default;
engine.mountExplorer(document.getElementById("explorer"), data);
})();
</script>
</body>
</html>
`;
writeFileSync(out, html);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB, ${modules.size} modules)`);
